/* ==========================================================================
   The instrument: a fixed stage, and the layers on it.

   This file owns the panel and nothing about chemistry. It reads
   layer-manifest.json, puts every layer where the manifest says, scales the
   whole thing to the viewport, and offers the parts the activity drives:
   keycaps, LED registers, sprite sheets and the identify readout.

   Positions appear here exactly once, in the manifest. If a number looks
   like a coordinate and is not in the manifest, it is wrong.
   ========================================================================== */

(function (global) {
  'use strict';

  var SAFE_W = 1600, SAFE_H = 1000;

  /* Draw order, back to front, from the spec. {s} expands once per station.

     One departure: the spec lists all the glass overlays together, before the
     viewports. A lens reflection under the lens is not a reflection, so
     glass-viewport-{s} is drawn immediately over its own viewport and the
     rest stay where the spec puts them. */
  var ORDER = [
    'bracket-{s}', 'stirplate-{s}',
    'refract-{s}', 'water-{s}', 'turbidity-{s}', 'pile-{s}',
    'sprite-stirbar-{s}', 'sprite-pour-{s}', 'sprite-powder-{s}',
    'head-{s}', 'beaker-{s}',
    'console',
    'register-panel-{s}',
    'display-readout', 'display-clock', 'display-counter-{s}',
    'register-leds-{s}',
    'glass-readout', 'glass-clock', 'glass-counter-{s}',
    'key-freeze', 'key-stir', 'key-reset', 'key-dispense', 'heat',
    'nameplate-{s}',
    'viewport-ring-{s}', 'viewport-field-{s}', 'glass-viewport-{s}',
    'notebook-paper', 'notebook-text'
  ];

  /* The wall, the trim and the bench are not stage layers: they have to run
     past the safe area, so the bleed behind the stage draws them. */
  /* Layers CSS needs by name rather than by box: the bleed tiles behind the
     stage. The register's lamps need the same treatment but there is one
     pair per substance, which only the activity knows, so it passes them in
     as `lamps`. Both go through url(), so both get the placeholder
     fallback. */
  var BLEED = ['wall', 'wall-trim', 'bench'];

  // Frames in each sprite sheet, as generated by tools/make-placeholders.py.
  var SPRITE_FRAMES = { stirbar: 12, pour: 8, powder: 8 };

  function el(tag, cls) {
    var node = document.createElement(tag);
    if (cls) node.className = cls;
    return node;
  }

  function Instrument(opts) {
    this.stage = opts.stage;
    this.base = opts.assets || 'assets/layers/';
    this.stations = opts.stations;
    this.lamps = opts.lamps || [];
    /* Matched against a built layer id to find its station. Built from the
       list rather than written out, because the written-out version named
       sugar and caco3: a station outside it got no data-station and no
       builder, and said nothing about it. */
    this.stationRe = new RegExp('-(' + opts.stations.join('|') + ')$');
    this.build = opts.build || {};
    this.onIdentify = opts.onIdentify || function () {};
    this.boxes = {};
    this.layers = {};
    this.sprites = {};
    this.geometry = opts.geometry || {};
    this.index = opts.index || null;
    this.present = opts.present || null;
    this.catalogue(opts.manifest);
  }

  /* Keycaps share one manifest row per key, named for both states at once
     ("key-freeze-up / key-freeze-down"), so each row is registered under
     every name it mentions plus the bare key id. */
  Instrument.prototype.catalogue = function (manifest) {
    for (var i = 0; i < manifest.length; i++) {
      var row = manifest[i];
      var names = row.id.split(' / ');
      for (var j = 0; j < names.length; j++) {
        var name = names[j].trim();
        this.boxes[name] = row;
        var bare = name.replace(/-(up|down|ready|spent)$/, '');
        if (!this.boxes[bare]) this.boxes[bare] = row;
      }
    }
  };

  Instrument.prototype.box = function (id) {
    var row = this.boxes[id];
    if (!row) throw new Error('no layer "' + id + '" in the manifest');
    return row.box_1x;
  };

  Instrument.prototype.render = function (id) {
    var row = this.boxes[id];
    return row ? row.render : 'code';
  };

  /* Layers that are the same picture at both stations share one file, so the
     id a layer is known by and the file it loads are not always the same
     name. The index says which; without one, every id is its own file.

     `present` says which files the set being loaded actually has; anything
     missing falls back to the placeholder set, so a part-finished set of
     renders still draws a whole bench. */
  Instrument.prototype.url = function (id) {
    var file = (this.index && this.index[id]) || id;
    var from = !this.present || this.present[file] ? this.base : PLACEHOLDER;
    return 'url("' + from + file + '.webp")';
  };

  /* ---- the stage -------------------------------------------------------- */

  /* Contain: the safe area is scaled to fit and centred, and the three
     numbers that come out of it are the only layout JS does. Everything else
     is in points, in CSS, from the manifest. */
  Instrument.prototype.fit = function () {
    var w = global.innerWidth, h = global.innerHeight;
    var s = Math.min(w / SAFE_W, h / SAFE_H);
    var root = document.documentElement.style;
    root.setProperty('--s', s);
    root.setProperty('--ox', ((w - SAFE_W * s) / 2) + 'px');
    root.setProperty('--oy', ((h - SAFE_H * s) / 2) + 'px');
    this.scale = s;
  };

  Instrument.prototype.mount = function () {
    var root = document.documentElement.style;
    var named = BLEED.concat(this.lamps);
    for (var i = 0; i < named.length; i++) {
      root.setProperty('--img-' + named[i], this.url(named[i]));
    }

    /* The same wall, trim and bench again, inside the stage this time.

       The stage is scaled, and a transform makes a stacking context, which
       makes an isolated group: a layer set to multiply blends only with its
       siblings, and the bleed behind the stage is not one of them. Without
       something underneath that is actually in here, photographed glass has
       nothing to darken and multiply does nothing at all.

       It is the identical picture on the identical tile grid, so the two are
       seamless; the bleed still does the work past the safe area. */
    var ground = el('div', 'ground');
    ground.setAttribute('aria-hidden', 'true');
    ground.appendChild(el('div', 'ground__wall'));
    ground.appendChild(el('div', 'ground__trim'));
    ground.appendChild(el('div', 'ground__bench'));
    this.stage.appendChild(ground);

    var ids = [];
    for (var j = 0; j < ORDER.length; j++) {
      var pattern = ORDER[j];
      if (pattern.indexOf('{s}') < 0) { ids.push(pattern); continue; }
      for (var k = 0; k < this.stations.length; k++) {
        ids.push(pattern.replace('{s}', this.stations[k]));
      }
    }
    for (var n = 0; n < ids.length; n++) this.place(ids[n]);
    this.fit();
    return this;
  };

  Instrument.prototype.place = function (id) {
    var box = this.box(id);
    var kind = this.render(id);
    var station = this.stationRe.exec(id);
    var custom = this.build[id] || this.build[id.replace(this.stationRe, '-{s}')];

    var node = el(custom && custom.tag ? custom.tag : 'div', 'layer');
    node.dataset.layer = id;
    node.dataset.render = kind;
    if (station) node.dataset.station = station[1];
    node.style.left = box[0] + 'px';
    node.style.top = box[1] + 'px';
    node.style.width = box[2] + 'px';
    node.style.height = box[3] + 'px';

    /* "raster x2" is a keycap: two files, one per state, and the key itself
       picks which. Asking for {id}.webp here would fetch a file that by
       design does not exist. */
    if (kind.indexOf('raster') === 0 && kind !== 'raster x2') {
      node.style.backgroundImage = this.url(id);
    }
    if (kind === 'sprite') this.dressSprite(node, id, box);

    /* A blend mode the layer asks for in the manifest. Photographed glass
       multiplies over what is behind it, which is how a transparent object
       composites without anyone having to mask the transparency by hand. */
    if (this.boxes[id] && this.boxes[id].blend) {
      node.style.mixBlendMode = this.boxes[id].blend;
    }

    this.stage.appendChild(node);
    this.layers[id] = node;
    if (custom && custom.make) custom.make.call(this, node, id, station && station[1]);
    return node;
  };

  /* ---- sprites ---------------------------------------------------------- */

  Instrument.prototype.dressSprite = function (node, id, box) {
    var kind = id.split('-')[1];
    var frames = SPRITE_FRAMES[kind] || 1;
    node.classList.add('sprite', 'sprite--' + kind);
    node.style.backgroundImage = this.url(id);
    node.style.setProperty('--frames', frames);
    node.style.setProperty('--frame-w', box[2] + 'px');
    node.style.setProperty('--frame', 0);

    var handle = {
      el: node,
      frames: frames,
      /* Phase in turns, so callers think in rotations rather than frames and
         a sprite can be driven from a clock or from the engine's own stir
         phase without either knowing the sheet length. */
      phase: function (turns) {
        var f = Math.floor(((turns % 1) + 1) % 1 * frames) % frames;
        node.style.setProperty('--frame', f);
      },
      show: function (on) { node.style.display = on ? '' : 'none'; }
    };
    handle.show(false);
    this.sprites[id] = handle;
    return handle;
  };

  /* ---- keycaps ---------------------------------------------------------- */

  /* A real button carrying the key's own art, one image up and one down.
     Pointer Events only: a touchscreen Chromebook is neither a desktop nor a
     phone, and a mouse-only handler fails on it in silence. */
  Instrument.prototype.key = function (id, opts) {
    var node = this.layers[id];
    node.classList.add('key');
    node.type = 'button';
    node.style.setProperty('--key-up', this.url(opts.up));
    node.style.setProperty('--key-down', this.url(opts.down));
    node.style.backgroundImage = '';
    node.setAttribute('aria-label', opts.label);
    if (opts.latching) node.setAttribute('aria-pressed', 'false');

    if (opts.legend) {
      var tag = el('span', 'key__legend');
      tag.textContent = opts.legend;
      tag.setAttribute('aria-hidden', 'true');
      node.appendChild(tag);
    }

    var self = this;
    var held = false;

    function down() {
      if (node.getAttribute('aria-disabled') === 'true' || opts.latching) return;
      held = true;
      node.classList.add('is-down');
    }
    function up() {
      if (!held) return;
      held = false;
      node.classList.remove('is-down');
    }

    node.addEventListener('pointerdown', down);
    node.addEventListener('pointerup', up);
    node.addEventListener('pointercancel', up);
    node.addEventListener('pointerleave', up);

    /* click, not pointerup: it is also what Enter and Space on a focused
       button send, so the keyboard path is the same path. */
    node.addEventListener('click', function (e) {
      e.preventDefault();
      /* Touch identifies whatever it activates, in the same tap — there is
         no hover to fall back on and no second tap to spend. */
      if (e.pointerType !== 'mouse') self.onIdentify(node.dataset.id);
      opts.press();
    });

    return {
      el: node,
      /* A latching key stays down until it is pressed again; a momentary one
         is pushed down for as long as the state it starts lasts.

         A finger still on the cap wins: this is called every frame, and
         without that the key would spring back up under a held pointer in
         the moment before the thing it starts has started. */
      set: function (on) {
        node.classList.toggle('is-down', !!on || held);
        if (opts.latching) node.setAttribute('aria-pressed', on ? 'true' : 'false');
      },
      /* aria-disabled, not the disabled property: a spent key is still worth
         identifying, and a disabled button receives no pointer events at
         all. The caller is what refuses the press. */
      enable: function (on) { node.setAttribute('aria-disabled', on ? 'false' : 'true'); },
      swap: function (upId, downId) {
        node.style.setProperty('--key-up', self.url(upId));
        node.style.setProperty('--key-down', self.url(downId));
      }
    };
  };

  /* ---- LED register ----------------------------------------------------- */

  /* One LED per particle, filled in reading order. The grid is 5 x 10 in the
     CSS because that is what the panel is engraved for; the count is checked
     against it rather than assumed. */
  Instrument.prototype.register = function (node, total) {
    node.classList.add('leds');
    var leds = [];
    for (var i = 0; i < total; i++) {
      var dot = el('i', 'led');
      node.appendChild(dot);
      leds.push(dot);
    }
    var lit = -1;
    var ceiling = 0;        // how many were lit when the current sweep began
    var sweeping = false;
    return {
      /* Only the LEDs that changed are touched: this runs every frame. */
      set: function (n) {
        sweeping = false;   // live readings resume; the next sweep starts fresh
        if (n === lit) return;
        var from = lit < 0 ? 0 : Math.min(lit, n);
        var to = lit < 0 ? total - 1 : Math.max(lit, n) - 1;
        for (var i = from; i <= to; i++) leds[i].classList.toggle('is-lit', i < n);
        lit = n;
      },
      /* Reset switches them off from the end backwards, so the panel reads as
         being cleared rather than simply going blank.

         The sweep runs over the LEDs that are actually lit, not over all
         fifty sockets: clearing six of them should take the same moment as
         clearing forty, or a half-empty register sits there doing nothing
         for most of the cascade and then empties all at once. */
      cascade: function (frac) {
        // The sweep's first frame is already a fraction of a second in, so
        // the ceiling is latched on first call rather than at frac === 1.
        if (!sweeping) { sweeping = true; ceiling = Math.max(lit, 0); }
        var keep = Math.round(ceiling * frac);
        for (var i = keep; i < ceiling; i++) leds[i].classList.remove('is-lit');
        if (lit > keep) lit = keep;
      }
    };
  };

  /* ---- identify --------------------------------------------------------- */

  /* Hover names a thing, focus names a thing, and a tap names a thing. One
     readout, three ways in. */
  Instrument.prototype.listen = function () {
    var self = this;

    this.stage.addEventListener('pointerover', function (e) {
      var hit = e.target.closest('[data-id]');
      if (hit) self.onIdentify(hit.dataset.id);
    });

    /* Only a mouse takes the name away again. A finger has nowhere to move
       the pointer to, so what it tapped stays named until it taps something
       else. */
    this.stage.addEventListener('pointerout', function (e) {
      if (e.pointerType !== 'mouse') return;
      var hit = e.target.closest('[data-id]');
      if (hit) self.onIdentify(null);
    });

    this.stage.addEventListener('focusin', function (e) {
      var hit = e.target.closest('[data-id]');
      if (hit) self.onIdentify(hit.dataset.id);
    });

    var fit = function () { self.fit(); if (self.onResize) self.onResize(); };
    global.addEventListener('resize', fit);
    if (global.visualViewport) global.visualViewport.addEventListener('resize', fit);
    global.addEventListener('orientationchange', fit);
    return this;
  };

  /* ---- boot ------------------------------------------------------------- */

  /* The manifest is fetched rather than inlined so that it stays the one
     source of truth Ben re-exports beside his renders. That needs a server:
     over file:// the browser refuses, and the activity says so plainly
     instead of showing an empty bench. */
  /* Two sets of art. `layers/` is the finished renders and is what ships;
     `layers-placeholder/` is the generated stand-ins. A layer loads from the
     finished set when that set has the file and from the placeholder set
     when it does not, so the bench is whole while renders are still being
     made one at a time.

     The debug menu can force the placeholder set for a whole page, to judge
     a new render against the one it replaces. ?assets=<folder> names a third
     set for a one-off, and beats the menu; its name is restricted to one
     path segment, since it comes from the URL. */
  var FINISHED = 'assets/layers/';
  var PLACEHOLDER = 'assets/layers-placeholder/';

  Instrument.boot = function (opts) {
    var want = /[?&]assets=([a-z0-9-]+)/i.exec(global.location.search);
    var forced = global.Kit && Kit.debug && Kit.debug.get('textures') === 'placeholder';
    var base = opts.assets = want ? 'assets/' + want[1] + '/'
             : forced ? PLACEHOLDER
             : (opts.assets || FINISHED);

    if (base !== FINISHED) document.title += ' — ' + (want ? want[1] : 'placeholder');

    /* What this set actually holds. The dev server answers `?list` with a
       directory as JSON, which is one request and no misses — asking for
       each file instead means a 404 per missing render, and the browser logs
       every one of them whatever the code does with the result.

       A real host answers no such question, so the set carries the answer:
       make-placeholders.py writes present.json beside the renders. Without
       it a part-finished set on a static host silently loads every layer
       from this folder, 404s on the forty that are not drawn yet, and comes
       up as a bench with almost nothing on it. That is what the first
       GitHub Pages deploy did.

       The live listing wins where there is one, so dropping a new export in
       still works without re-running anything. */
    function listing() {
      if (base === PLACEHOLDER) return Promise.resolve(null);
      return fetch(base + '?list').then(function (r) {
        var type = r.headers.get('content-type') || '';
        if (!r.ok || type.indexOf('json') < 0) return null;
        /* An array or nothing. GitHub Pages ignores the query string and
           answers this with index.json — 200, and genuinely JSON, but an
           object, which used to reach forEach and take the whole page down
           with "names.forEach is not a function". A local static server
           returns the directory as HTML instead and never got that far, so
           only the real host showed it. */
        return r.json().then(function (j) { return Array.isArray(j) ? j : null; },
                             function () { return null; });
      }, function () { return null; }).then(function (names) {
        if (names) return names;
        return fetch(base + 'present.json').then(function (r) {
          return r.ok ? r.json() : null;
        }, function () { return null; });
      });
    }

    return listing().then(function (names) {
      /* geometry and index describe the layout rather than the pictures, so
         a set holding nothing but new .webp files borrows the placeholder
         set's — which is where make-placeholders.py writes them. */
      function beside(name) {
        var from = !names || names.indexOf(name) >= 0 ? base : PLACEHOLDER;
        return fetch(from + name).then(function (r) { return r.json(); });
      }

      var present = null;
      if (names) {
        present = {};
        names.forEach(function (n) {
          if (/\.webp$/.test(n)) present[n.replace(/\.webp$/, '')] = true;
        });
        console.log('assets: ' + Object.keys(present).length + ' from ' + base +
                    ', the rest from ' + PLACEHOLDER);
      }

      return Promise.all([
        fetch(opts.manifest).then(function (r) { return r.json(); }),
        beside('geometry.json'),
        beside('index.json')
      ]).then(function (all) {
        opts.manifest = all[0];
        opts.geometry = all[1];
        opts.index = all[2];
        opts.present = present;
        return new Instrument(opts).mount().listen();
      });
    });
  };

  Instrument.SAFE_W = SAFE_W;
  Instrument.SAFE_H = SAFE_H;
  global.Instrument = Instrument;
})(window);
